const normalizeCategoryToken = (value) => {
  if (typeof value !== "string") return "";

  return value
    .trim()
    .toLowerCase()
    .replace(/&/g, "و")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/[^\p{L}\p{N}\-]+/gu, "")
    .replace(/^-+|-+$/g, "");
};

export function getCategoryIconKey(category) {
  const candidates = [];

  if (typeof category === "string") {
    candidates.push(category);
  } else if (category && typeof category === "object") {
    candidates.push(category.slug, category.key, category.name, category.label);
  }

  for (const candidate of candidates) {
    const normalized = normalizeCategoryToken(candidate);
    if (!normalized) continue;

    const direct = CATEGORY_ICON_BY_SLUG[normalized] || CATEGORY_ICON_ALIASES[normalized];
    if (direct) return direct;
  }

  return null;
}
